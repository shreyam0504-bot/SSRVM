@app.route("/api/chatbot", methods=["POST"])
def api_chatbot():
    if not current_user():
        return jsonify({"error": "unauthorized"}), 401

    data = request.get_json() or {}
    text = (data.get("text", "") or "").strip()
    text_l = text.lower()

    # Emotion/distress word lists — defined here (not just inline further down)
    # so the follow-up state check below can also use them to detect a genuine
    # new distress signal that should override whatever the bot was waiting for.
    sadness_words = ["sad", "upset", "down", "hurt", "cry", "crying", "depressed",
                      "heartbroken", "miserable", "empty", "numb", "feeling low",
                      "crying myself to sleep", "can't stop crying"]
    anger_words = ["angry", "mad", "annoyed", "pissed", "frustrated", "irritated",
                   "furious", "fed up", "sick of this", "can't stand it"]
    anxiety_words = ["anxious", "scared", "worried", "nervous", "panic", "panic attack",
                      "freaking out", "can't breathe", "on edge", "restless"]
    overthinking_words = ["overthink", "overthinking", "thoughts won't stop",
                            "can't stop thinking", "ruminating", "spiraling",
                            "stuck in my head", "racing thoughts"]
    loneliness_words = ["lonely", "alone", "isolated", "no one understands",
                          "nobody cares", "left out", "no friends"]
    stress_words = ["stressed", "pressure", "overwhelmed", "too much", "burnout",
                      "can't cope", "drowning", "breaking down", "burnt out",
                      "no motivation", "can't keep up", "falling behind"]
    distress_keywords = [
        "stress", "stressed", "anxious", "panic", "hopeless", "sad",
        "depressed", "overwhelmed", "guilty", "ashamed", "angry",
        "lonely", "tired", "exhausted", "worthless", "fear", "worry",
        "uneasy", "scared", "pressure", "burnout", "give up", "empty",
        "numb", "can't sleep", "insomnia"
    ]
    all_distress_words = (
        sadness_words + anger_words + anxiety_words + overthinking_words
        + loneliness_words + stress_words + distress_keywords
    )

    # ---------------- CRISIS PHRASE DETECTION ----------------
    # Crisis phrases always take priority, even mid-activity, so this check
    # stays first regardless of what the bot was waiting for.
    if any(p in text_l for p in CRISIS_PHRASES):
        try:
            conn = get_db()
            cur = conn.cursor()
            cur.execute(
                "INSERT INTO counsellor_requests (user_id, message, want_counsellor, auto_notify) VALUES (?, ?, ?, ?)",
                (current_user()["id"], text, 1, 1)
            )
            counsellor_request_id = cur.lastrowid
            conn.commit()
            conn.close()
        except Exception:
            counsellor_request_id = None

        # Notify counsellor automatically
        notify_outcomes = notify_counsellor(current_user(), text, counsellor_request_id)

        # Crisis response
        reply_text = (
            "It sounds like you’re in serious distress. Please talk to someone you trust or reach out to your counsellor immediately. "
            "You are not alone — your counsellor/student support team has been notified and will reach out soon. "
            "If you’re in immediate danger, please contact local emergency services right away."
        )

        resp = {
            "reply": reply_text,
            "crisis": True,
            "notified": any(o.get("success") for o in notify_outcomes)
        }
        if os.environ.get("SSRVM_DEBUG_NOTIFY") == "1":
            resp["notify_debug"] = notify_outcomes
        return jsonify(resp), 200

    # ---------------- FOLLOW-UP STATE CHECK ----------------
    # If the bot just offered a specific activity (grounding, breathing, etc.)
    # OR just asked a follow-up question (like "how are you feeling now?"),
    # treat this message as the answer to THAT, instead of re-running the full
    # keyword cascade on it. This fixes cases like:
    #   bot: "name 5 things you can see"        -> user: "flowers, bottle, ..."
    #   bot: "how's your body feeling now?"      -> user: "better"
    # which previously matched nothing and fell through to the Gemini fallback.
    awaiting = session.pop("awaiting", None)
    has_real_distress_signal = matched_phrases(text_l, all_distress_words)

    if awaiting and has_real_distress_signal:
        # Something genuinely concerning came up mid-activity — don't swallow it
        # into a generic "how are you feeling" reply. Let it fall through to the
        # normal emotion cascade below, which handles it properly.
        pass
    elif awaiting and text_l in ("no", "nope", "nah", "na"):
        return jsonify({
            "reply": "That's okay. I'm still right here with you. What would make things feel a little lighter?",
            "ask_counsellor": False,
            "crisis": False
        }), 200
    elif awaiting and text_l not in ("", ):
        # Activities that end by asking "how are you feeling now?" — the reply to
        # THAT question is handled by the "mood_check" branch below, so we set
        # the next awaiting state here rather than letting the chain dead-end.
        activity_acks = {
            "grounding_5things": (
                "Nice — naming those things means you're bringing your focus back to "
                "the present moment, which is exactly the point. How are you feeling now?"
            ),
            "breathing_444": (
                "Good job working through that breathing cycle. How's it feel now — "
                "any calmer?"
            ),
            "breathing_soft": (
                "Well done — a few slow breaths can shift a lot. How's your body feeling now?"
            ),
            "generic_activity": (
                "Thanks for sharing that. How are you feeling now, a little lighter or still heavy?"
            ),
        }
        if awaiting == "heaviest_step":
            # This one asks the student to name a next action, not a mood —
            # no further "how do you feel" chain needed, so no new awaiting set.
            return jsonify({
                "reply": (
                    "That's a solid first step. Try just focusing on that one thing — "
                    "you don't have to solve everything at once."
                ),
                "ask_counsellor": False,
                "crisis": False
            }), 200
        if awaiting == "mood_check":
            positive_words = ["better", "good", "okay", "ok", "fine", "calmer", "lighter", "great", "relaxed"]
            negative_words = ["worse", "bad", "same", "still", "heavy", "not good", "no better"]
            if any(w in text_l for w in positive_words):
                reply_text = "That's really good to hear. Keep going at your own pace — I'm here whenever you need me."
            elif any(w in text_l for w in negative_words):
                reply_text = (
                    "Thanks for being honest — sometimes it takes more than one exercise. "
                    "Would you like to try another grounding technique, or talk to a counsellor?"
                )
            else:
                reply_text = "Thanks for telling me. I'm here whenever you want to talk more or try something else."
            return jsonify({
                "reply": reply_text,
                "ask_counsellor": False,
                "crisis": False
            }), 200
        # Default: give the activity's ack, and mark that we're now waiting on
        # the mood-check question it asks.
        session["awaiting"] = "mood_check"
        return jsonify({
            "reply": activity_acks.get(awaiting, activity_acks["generic_activity"]),
            "ask_counsellor": False,
            "crisis": False
        }), 200

    # ---------------- EMOTION-BASED REPLIES ----------------
    if matched_phrases(text_l, sadness_words):
        return jsonify({
            "reply": random.choice([
                "I’m really sorry you’re feeling this heavy. That kind of sadness can drain your energy. "
                "You’re not alone — I’m right here with you. Would grounding or a short breathing exercise help right now?",
                "That sounds really painful to carry. You don’t have to hold it alone right now. "
                "Want to try a short grounding exercise, or just keep talking it through?",
                "I hear you. Sadness like that can feel heavy in your whole body, not just your mind. "
                "Would it help to write it out in your journal, or try a calming exercise?",
            ]),
            "ask_counsellor": True,
            "crisis": False
        }), 200

    if matched_phrases(text_l, anger_words):
        return jsonify({
            "reply": random.choice([
                "It’s okay to feel angry — it usually means something important is happening inside you. "
                "You don’t have to hold it alone. Do you want help calming down, or do you want to talk about what triggered it?",
                "That frustration sounds real and valid. Want to vent about what happened, or try something to cool down first?",
                "Anger like that is usually a signal something matters to you. I’m here either way — talk it out or calm down first?",
            ]),
            "ask_counsellor": True,
            "crisis": False
        }), 200

    if matched_phrases(text_l, anxiety_words):
        return jsonify({
            "reply": random.choice([
                "That sounds overwhelming. Anxiety can make everything feel heavier than it is. "
                "You’re safe here. Want to try a short breathing exercise together?",
                "That's a lot to carry. Your body might be in fight-or-flight mode right now — want to try slowing your breathing together?",
                "I hear how on-edge you feel. You're safe right now. Want a quick grounding or breathing exercise?",
            ]),
            "ask_counsellor": True,
            "crisis": False
        }), 200

    if matched_phrases(text_l, overthinking_words):
        return jsonify({
            "reply": random.choice([
                "Overthinking can trap you in loops that feel impossible to break. "
                "I’m here with you — you don’t have to fight your thoughts alone. Would a grounding technique help right now?",
                "Racing thoughts can be exhausting. Let's try to slow things down together — want a grounding exercise?",
                "Your mind sounds like it's stuck on repeat. Sometimes naming what you see around you helps break the loop — want to try that?",
            ]),
            "ask_counsellor": True,
            "crisis": False
        }), 200

    if matched_phrases(text_l, loneliness_words):
        return jsonify({
            "reply": random.choice([
                "Feeling lonely can hurt so much. I’m really glad you reached out instead of staying silent. "
                "You’re not alone here — I’m with you. Would you like to talk about what’s been making you feel this way?",
                "That sounds isolating. I'm glad you're talking to me right now. Want to share more about what's going on?",
                "Loneliness is heavy, even when people are around you. I'm here and listening — what's been on your mind?",
            ]),
            "ask_counsellor": True,
            "crisis": False
        }), 200

    if matched_phrases(text_l, stress_words):
        return jsonify({
            "reply": random.choice([
                "Feeling overwhelmed takes a lot out of you. You’re doing your best. "
                "Let’s take it one tiny step at a time. Would you like a small reset activity or grounding exercise?",
                "That's a lot of pressure to carry. Let's break it down — want a quick reset activity first?",
                "Sounds like you're stretched thin right now. One small step at a time is enough — want a grounding exercise to reset?",
            ]),
            "ask_counsellor": True,
            "crisis": False
        }), 200

    # ---------------- FALLBACK DISTRESS WORDS ----------------
    if matched_phrases(text_l, distress_keywords):
        coping_suggestions = [
            "Try 4–4–4 breathing — inhale 4s, hold 4s, exhale 4s.",
            "Write your feelings in your journal. It often helps you understand your emotions.",
            "Take a short walk, drink some water, or listen to calming music.",
            "Reach out to someone you trust — even a small chat can make a difference.",
            "Remember to take things one step at a time. You’re doing your best."
        ]
        return jsonify({
            "reply": random.choice(coping_suggestions) +
                     " Would you like me to notify a counsellor so they can reach out to support you?",
            "ask_counsellor": True,
            "crisis": False
        }), 200

    # ---------------- YES / NO FOLLOW-UP HANDLERS ----------------
    yes_words = ["yes", "yeah", "yep", "sure", "ok", "okay", "yea", "yaa"]
    no_words = ["no", "nope", "nah", "na"]

    if text_l in yes_words:
        followups = [
            ("Try a 4–4–4 breathing cycle: inhale 4s, hold 4s, exhale 4s. Want me to guide you?", "breathing_444"),
            ("Here’s a grounding idea: name 5 things you can see. It helps bring your mind back.", "grounding_5things"),
            ("You're doing great. Try one slow deep breath… want another calming activity?", "breathing_soft"),
            ("Let's take it one step at a time — what part feels the heaviest right now?", "heaviest_step"),
            ("Put your hand on your chest and take 3 slow breaths. Want another soothing exercise?", "breathing_soft"),
        ]
        reply_text, awaiting_tag = random.choice(followups)
        session["awaiting"] = awaiting_tag
        return jsonify({
            "reply": reply_text,
            "ask_counsellor": False,
            "crisis": False
        }), 200

    if text_l in no_words:
        return jsonify({
            "reply": "That's okay. I'm still right here with you. What would make things feel a little lighter?",
            "ask_counsellor": False,
            "crisis": False
        }), 200

    # ---------------- NORMAL GEMINI CHAT ----------------
    g = analyze_with_gemini_generate(text)

    if g is None:
        return jsonify({
            "reply": "I'm still here for you — tell me what’s been on your mind. The assistant service is temporarily unavailable, but you can keep sharing how you feel.",
            "error": "gemini_unavailable"
        }), 503

    reply = g.get("reply", "").strip() or "I'm here — tell me more."
    score = float(g.get("score", 0))
    risk = bool(g.get("risk", False))
    summary = g.get("summary", "") or ""

    response = {
        "reply": reply,
        "ask_counsellor": score < -0.3 or risk,
        "summary": summary,
        "score": score,
        "risk": risk
    }

    return jsonify(response), 200

