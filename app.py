def quick_sentiment(text: str):
    text = (text or "").lower()
    neg = sum(1 for w in NEG_WORDS if w in text)
    pos = sum(1 for w in POS_WORDS if w in text)
    return pos - neg

# ---------------- Chatbot matching helpers ----------------
# Word-boundary matching avoids accidental substring hits (e.g. "mad" inside
# "madras"), and the negation check avoids treating "not sad anymore" or
# "don't feel anxious" the same as an actual sadness/anxiety statement.
_NEGATION_CUES = ["not", "n't", "no longer", "never", "stopped", "don't",
                  "doesn't", "isn't", "wasn't", "aren't", "won't", "wouldn't"]

def _phrase_present(text_l: str, phrase: str) -> bool:
    pattern = r"(?<!\w)" + re.escape(phrase) + r"(?!\w)"
    return re.search(pattern, text_l) is not None

def _negated_nearby(text_l: str, phrase: str, window: int = 4) -> bool:
    idx = text_l.find(phrase)
    if idx == -1:
        return False
    preceding = " ".join(text_l[:idx].split()[-window:])
    return any(cue in preceding for cue in _NEGATION_CUES)

def matched_phrases(text_l: str, phrases) -> bool:
    """True if any phrase genuinely applies (present and not negated just before it)."""
    for p in phrases:
        if _phrase_present(text_l, p) and not _negated_nearby(text_l, p):
            return True
    return False

def emotion_summary(user_id):
    conn = get_db()
    cur = conn.cursor()
    cur.execute("SELECT content FROM journals WHERE user_id=?", (user_id,))
    rows = cur.fetchall() or []
    conn.close()
    text = " ".join(r["content"].lower() for r in rows)
    cluster = {
        "stress": ["stress","overwhelmed","anxious","exam","pressure"],
        "sad": ["sad","lonely","tired","upset","down"],
        "anger": ["angry","frustrated","irritated"],
        "positive": ["happy","proud","good","hopeful","calm"]
    }
    score = {k:0 for k in cluster}
    for cat, words in cluster.items():
        for w in words:
            score[cat] += text.count(w)
    summary = ""
    if score["stress"]>0: summary += "There are signs of stress or exam pressure. "
    if score["sad"]>0: summary += "Some entries show sadness or emotional fatigue. "
    if score["anger"]>0: summary += "A few moments of frustration or irritation were noted. "
    if score["positive"]>0: summary += "You also showed hopeful or positive moments. "
    if summary == "": summary = "No strong emotional patterns detected. Keep journaling regularly."
    return summary

